//! Structural traversal is independent of serialization and required-field lists.
use super::model::*;
use schemars::JsonSchema;
use serde::Serialize;
use serde_json::Value;
use std::collections::BTreeMap;

#[path = "traversal.rs"]
mod traversal;

pub(crate) fn schema<T: JsonSchema>() -> Value {
    let generator = schemars::generate::SchemaSettings::draft2020_12()
        .with(|settings| settings.inline_subschemas = true)
        .into_generator();
    serde_json::to_value(generator.into_root_schema_for::<T>())
        .expect("Rust schema serializes as JSON")
}

#[derive(Default, Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Catalogue {
    pub fields: BTreeMap<String, Field>,
    pub exclusions: Vec<Exclusion>,
    pub gaps: Vec<InventoryGap>,
    pub collections: Vec<Collection>,
}

impl Catalogue {
    pub(crate) fn register<T: JsonSchema + Serialize>(
        &mut self,
        store: &str,
        owner: &str,
        defaults: Option<&T>,
        availability: Availability,
    ) -> Result<(), CatalogueError> {
        let defaults = defaults
            .map(serde_json::to_value)
            .transpose()
            .map_err(|_| error(store, "", "cannot serialize defaults"))?;
        self.register_schema(
            store,
            owner,
            &schema::<T>(),
            defaults.as_ref(),
            availability,
        )
    }

    /// Register a complete owner schema; a failed registration adds no partial fields.
    pub fn register_schema(
        &mut self,
        store: &str,
        owner: &str,
        schema: &Value,
        defaults: Option<&Value>,
        availability: Availability,
    ) -> Result<(), CatalogueError> {
        if store.is_empty() || owner.is_empty() || self.fields.values().any(|f| f.store == store) {
            return Err(error(store, "", "invalid or duplicate store"));
        }
        let mut pending = Self::default();
        pending.walk(store, owner, "", schema, defaults, None, &availability)?;
        self.fields.extend(pending.fields);
        self.exclusions.extend(pending.exclusions);
        self.gaps.extend(pending.gaps);
        self.collections.extend(pending.collections);
        Ok(())
    }

    /// Append the owner ledger and validate every gap, including schema-derived gaps.
    pub(crate) fn register_gap_ledger(&mut self, source: &str) -> Result<(), CatalogueError> {
        self.gaps.extend(
            serde_json::from_str::<Vec<InventoryGap>>(source)
                .map_err(|_| error("inventory", "/gaps", "invalid gap ledger"))?,
        );
        for gap in &self.gaps {
            gap.validate()?;
        }
        Ok(())
    }

    /// Gate for the later cutover: an owner gap must never become silent coverage.
    pub fn require_complete_inventory(&self) -> Result<(), CatalogueError> {
        for gap in &self.gaps {
            gap.validate()?;
        }
        if let Some(gap) = self.gaps.first() {
            return Err(error(
                &gap.store,
                &gap.path,
                "inventory incomplete; resolve owner gaps before cutover",
            ));
        }
        Ok(())
    }

    /// Serialize the exact Rust descriptors for frontend rendering.
    pub fn typescript(&self) -> Result<String, serde_json::Error> {
        Ok(format!(
            "// Generated from Rust settings schemas. Do not edit.\n// biome-ignore-all format: Rust owns the generated byte format.\nexport const settingsCatalogue = {} as const;\n",
            serde_json::to_string_pretty(self)?
        ))
    }
}

pub(super) fn error(store: &str, path: &str, reason: &str) -> CatalogueError {
    CatalogueError {
        store: store.into(),
        path: path.into(),
        reason: reason.into(),
    }
}

