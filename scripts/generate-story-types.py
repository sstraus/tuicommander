#!/usr/bin/env python3
"""Generate story wire enums from Rust's unit enums; reject unsupported serde syntax."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src/types/stories.gen.ts"


def generate():
    source = (ROOT / "src-tauri/src/stories/model.rs").read_text()
    declarations = []
    for name in ("StoryStatus", "PlanState", "StoryType", "StoryVisibility", "StoryRisk"):
        match = re.search(
            rf'#\[serde\(rename_all = "snake_case"\)\]\s*pub enum {name} \{{([^}}]+)\}}',
            source,
        )
        if not match:
            raise ValueError(f"Unsupported serde declaration for {name}")
        variants = []
        for line in match[1].strip().splitlines():
            if line.strip() == "#[default]":
                continue
            variant = re.fullmatch(r"\s*(\w+),\s*", line)
            if not variant:
                raise ValueError(f"Unsupported {name} variant: {line}")
            value = re.sub(r"(?<!^)([A-Z])", r"_\1", variant[1]).lower()
            variants.append(f'"{value}"')
        declarations.append(f"export type {name} = " + " | ".join(variants) + ";")
    return "// Generated by scripts/generate-story-types.py. Do not edit.\n\n" + "\n".join(declarations) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if OUTPUT.read_text() != generated:
            raise SystemExit("Story types drift: run python3 scripts/generate-story-types.py")
    else:
        OUTPUT.write_text(generated)
